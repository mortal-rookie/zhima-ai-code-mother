/**
 * 上传头像 POST /user/avatar/upload
 *
 * 入参是 FormData，字段名必须是 file（和后端 @RequestParam("file") 对齐）。
 * 返回 data 是图片在 COS 上的访问地址，前端把它填进表单，用户再点保存才会写入用户资料。
 */
export async function uploadAvatar(body: FormData, options?: { [key: string]: any }) {
  return request<API.BaseResponseString>('/user/avatar/upload', {
    method: 'POST',
    data: body,
    // 千万不要手写 'Content-Type': 'multipart/form-data'：
    // 少了 boundary 后端会直接报 400/415，必须让浏览器/axios 自己带上
    ...(options || {}),
  })
}
